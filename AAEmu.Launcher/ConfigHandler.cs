
using System.Text;

namespace AAEmu.Launcher
{
    internal static class ConfigHandler
    {
        private static readonly byte[] CipherBytes =
            new byte[]
            {
                0x45, 0x41, 0x56, 0x09, 0x5B, 0x36, 0x1E, 0x0E, 0x16, 0x03, 0x10, 0x19, 0x20, 0x13, 0x07, 0x1C,
                0x0A, 0x37, 0x22, 0x0D, 0x38, 0x2D, 0x08, 0x1B, 0x4D, 0x0B, 0x58, 0x17, 0x0F, 0x55, 0x06, 0x53,
                0x0C, 0x46, 0x12, 0x2E, 0x43, 0x25, 0x54, 0x32, 0x3D, 0x2F, 0x5D, 0x39, 0x30, 0x15, 0x23, 0x29,
                0x2C, 0x35, 0x27, 0x3F, 0x59, 0x31, 0x05, 0x11, 0x14, 0x2B, 0x3C, 0x51, 0x3A, 0x28, 0x50, 0x33,
                0x42, 0x01, 0x40, 0x24, 0x47, 0x00, 0x21, 0x44, 0x4A, 0x4E, 0x48, 0x4C, 0x4B, 0x18, 0x49, 0x52,
                0x3E, 0x3B, 0x4F, 0x1F, 0x26, 0x1D, 0x02, 0x5A, 0x1A, 0x34, 0x57, 0x04, 0x5E, 0x2A, 0x5C, 0x00
            };

        public static string ApplyCipher(string input)
        {
            // Do not apply to comment lines
            if (input.StartsWith("--"))
                return input;
            var inputBytes = Encoding.UTF8.GetBytes(input);
            var outputBytes = new byte[inputBytes.Length];
            for (int i = 0; i < inputBytes.Length; i++)
            {
                if (inputBytes[i] >= 0x20 && inputBytes[i] < 0x80)
                {
                    outputBytes[i] = (byte)(CipherBytes[inputBytes[i] - 0x20] + 0x20);
                }
                else
                {
                    outputBytes[i] = inputBytes[i];
                }
            }
            return Encoding.UTF8.GetString(outputBytes);
        }
    }
}
